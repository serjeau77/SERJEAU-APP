export function formatCOP(value: number): string {
  return new Intl.NumberFormat('es-CO', {
    style: 'currency',
    currency: 'COP',
    maximumFractionDigits: 0,
  }).format(Math.round(value || 0));
}

export function formatNumber(value: number): string {
  return new Intl.NumberFormat('es-CO', {
    maximumFractionDigits: 1,
  }).format(value || 0);
}

export function sumCostBreakdown(c: CostBreakdown): number {
  return (
    (c.conductorCost || 0) +
    (c.combustible || 0) +
    (c.peajes || 0) +
    (c.seguridadSocial || 0) +
    (c.mantenimiento || 0) +
    (c.impuestos || 0) +
    (c.cuotaFinanciacion || 0) +
    (c.otros || 0)
  );
}

export function calculateFinancialMetrics(tarifa: number, costos: CostBreakdown, km: number) {
  const costoTotal = sumCostBreakdown(costos);
  const utilidadReal = tarifa - costoTotal;
  const margenPct = tarifa > 0 ? (utilidadReal / tarifa) * 100 : 0;
  const ingresoPorKm = km > 0 ? tarifa / km : 0;
  const costoPorKm = km > 0 ? costoTotal / km : 0;
  const utilidadPorKm = km > 0 ? utilidadReal / km : 0;

  return {
    tarifa,
    costoTotal,
    utilidadReal,
    margenPct,
    ingresoPorKm,
    costoPorKm,
    utilidadPorKm,
  };
}

export function estimateDefaultCosts(
  tarifa: number,
  km: number,
  vehicleType: VehicleType,
  conductorPct = 25
): CostBreakdown {
  const fuelRatePerKm = vehicleType === 'Logan' ? 420 : vehicleType === 'Duster' ? 510 : 680;
  const maintRatePerKm = vehicleType === 'Logan' ? 180 : vehicleType === 'Duster' ? 230 : 320;
  const conductorCost = Math.round((tarifa * conductorPct) / 100);
  const combustible = Math.round(km * fuelRatePerKm);
  const mantenimiento = Math.round(km * maintRatePerKm);
  const peajes = Math.round(km > 120 ? Math.floor(km / 95) * 18500 : 0);
  const seguridadSocial = Math.round(tarifa * 0.045);
  const impuestos = Math.round(tarifa * 0.035);
  const cuotaFinanciacion = Math.round(tarifa * 0.09);
  const otros = Math.round(tarifa * 0.025);

  return {
    conductorPct,
    conductorCost,
    combustible,
    peajes,
    seguridadSocial,
    mantenimiento,
    impuestos,
    cuotaFinanciacion,
    otros,
  };
}

